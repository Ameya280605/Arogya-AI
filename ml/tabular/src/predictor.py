"""Arogya AI - Standalone Tabular Baseline Predictor.

Module 9: Tabular ML Baseline Classification.
Provides programmatic and CLI inference for the trained Exasens baseline classifier,
including cryptographic checksum validation, schema checking, fallback imputation,
and explicit non-diagnostic research labeling.

SAFETY & GOVERNANCE NOTICE:
Outputs represent research prototype scores and NOT clinically certified diagnoses.
Probabilities reflect algorithm output distributions and must NOT be treated as
clinically validated risk metrics.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import logging
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any, Sequence

import joblib
import numpy as np
import pandas as pd
from sklearn.pipeline import Pipeline

from ml.tabular.src.dataset import ALL_FEATURES, BIOSENSOR_FEATURES, DEMOGRAPHIC_FEATURES, DIAGNOSIS_CLASSES

logger = logging.getLogger(__name__)

ARTIFACTS_DIR = Path(__file__).resolve().parent.parent / "artifacts"
DEFAULT_MODEL_PATH = ARTIFACTS_DIR / "tabular_baseline.joblib"
DEFAULT_METADATA_PATH = ARTIFACTS_DIR / "model_metadata.json"

RESEARCH_DISCLAIMER: str = (
    "RESEARCH PROTOTYPE ONLY: This prediction is generated by an experimental research model "
    "trained on benchmark data. It has NOT been clinically validated or approved by regulatory bodies. "
    "Outputs must NEVER be used for clinical diagnosis, treatment decisions, or emergency triage. "
    "Probabilities represent raw model distribution scores and are NOT clinically calibrated disease risks."
)


@dataclass(frozen=True)
class PredictionResult:
    """Structured container for single patient tabular inference."""

    predicted_class: str
    class_probabilities: dict[str, float]
    features_used: dict[str, Any]
    imputed_features: list[str]
    model_name: str
    model_version: str
    is_research_prototype: bool = True
    disclaimer: str = RESEARCH_DISCLAIMER

    def to_dict(self) -> dict[str, Any]:
        """Convert prediction result to standard serializable dictionary."""
        return asdict(self)


class TabularPredictor:
    """Standalone inference engine for tabular respiratory biomarker classification.

    Enforces:
    - Pre-load SHA-256 integrity validation against recorded metadata.
    - Strict input boundary and type validation.
    - Imputation of missing or unmeasured biosensor signals.
    - Research-only envelope formatting.
    """

    def __init__(
        self,
        model_path: Path | str | None = None,
        metadata_path: Path | str | None = None,
        verify_checksum: bool = True,
    ) -> None:
        """Initialize the predictor by loading and verifying the model artifact.

        Args:
            model_path: Path to serialized joblib pipeline. Defaults to DEFAULT_MODEL_PATH.
            metadata_path: Path to model metadata JSON. Defaults to DEFAULT_METADATA_PATH.
            verify_checksum: Whether to enforce SHA-256 checksum matching before loading.

        Raises:
            FileNotFoundError: If model or metadata file is not found.
            ValueError: If SHA-256 checksum verification fails.
        """
        self.model_path = Path(model_path) if model_path is not None else DEFAULT_MODEL_PATH
        self.metadata_path = Path(metadata_path) if metadata_path is not None else DEFAULT_METADATA_PATH

        if not self.model_path.exists():
            raise FileNotFoundError(f"Model artifact not found at: {self.model_path}")
        if not self.metadata_path.exists():
            raise FileNotFoundError(f"Metadata file not found at: {self.metadata_path}")

        with open(self.metadata_path, "r", encoding="utf-8") as f:
            self.metadata: dict[str, Any] = json.load(f)

        if verify_checksum:
            self._verify_sha256_checksum()

        self.pipeline: Pipeline = joblib.load(self.model_path)
        self.model_name: str = self.metadata.get("model_name", "tabular_exasens_baseline")
        self.model_version: str = self.metadata.get("model_version", "0.1.0-alpha")
        self.feature_names: list[str] = self.metadata.get("features", ALL_FEATURES)
        self.classes: list[str] = list(getattr(self.pipeline, "classes_", DIAGNOSIS_CLASSES))

    def _verify_sha256_checksum(self) -> None:
        """Verify that the model file matches the expected SHA-256 hash in metadata."""
        expected_hash = self.metadata.get("sha256_checksum")
        if not expected_hash:
            raise ValueError(f"Metadata at {self.metadata_path} lacks 'sha256_checksum' field.")

        sha256 = hashlib.sha256()
        with open(self.model_path, "rb") as f:
            while chunk := f.read(65536):
                sha256.update(chunk)
        actual_hash = sha256.hexdigest()

        if actual_hash.lower() != expected_hash.lower():
            raise ValueError(
                f"Artifact integrity compromised! Checksum mismatch for {self.model_path}.\n"
                f"Expected: {expected_hash}\n"
                f"Actual:   {actual_hash}"
            )

    @staticmethod
    def validate_input_dict(input_dict: dict[str, Any]) -> dict[str, Any]:
        """Validate single patient input data types, ranges, and mandatory fields.

        Args:
            input_dict: Dictionary containing input attributes.

        Returns:
            Sanitized dictionary with canonical feature keys.

        Raises:
            ValueError: If mandatory features are missing or values fall outside physiological bounds.
        """
        # 1. Mandatory demographic validation
        for field in DEMOGRAPHIC_FEATURES:
            if field not in input_dict or input_dict[field] is None:
                raise ValueError(f"Missing mandatory demographic feature '{field}'.")

        # Validate Age
        try:
            age = int(input_dict["Age"])
        except (ValueError, TypeError):
            raise ValueError(f"Age must be an integer, got: {input_dict['Age']!r}")
        if not (1 <= age <= 120):
            raise ValueError(f"Age {age} falls outside physiological range [1, 120].")

        # Validate Gender
        gender_val = input_dict["Gender"]
        if isinstance(gender_val, str):
            g_str = gender_val.strip().lower()
            if g_str in ("1", "male", "m"):
                gender = 1
            elif g_str in ("0", "female", "f"):
                gender = 0
            else:
                raise ValueError(f"Invalid Gender '{gender_val}'. Must be 1/Male or 0/Female.")
        else:
            try:
                gender = int(gender_val)
            except (ValueError, TypeError):
                raise ValueError(f"Gender must be 0 or 1, got: {gender_val!r}")
            if gender not in (0, 1):
                raise ValueError(f"Gender must be 0 (Female) or 1 (Male), got: {gender}")

        # Validate Smoking
        try:
            smoking = int(input_dict["Smoking"])
        except (ValueError, TypeError):
            raise ValueError(f"Smoking must be an integer (1, 2, 3), got: {input_dict['Smoking']!r}")
        if smoking not in (1, 2, 3):
            raise ValueError(f"Smoking status must be in {1, 2, 3} (1=Non-smoker, 2=Ex-smoker, 3=Active-smoker), got: {smoking}")

        validated: dict[str, Any] = {
            "Age": age,
            "Gender": gender,
            "Smoking": smoking,
        }

        # 2. Biosensor readings (optional, float or NaN)
        for b_col in BIOSENSOR_FEATURES:
            val = input_dict.get(b_col)
            if val is None or (isinstance(val, (float, np.floating)) and np.isnan(val)):
                validated[b_col] = np.nan
            else:
                try:
                    fval = float(val)
                    validated[b_col] = fval
                except (ValueError, TypeError):
                    raise ValueError(f"Biosensor feature '{b_col}' must be numeric float, got: {val!r}")

        return validated

    def predict_single(self, input_data: dict[str, Any]) -> PredictionResult:
        """Execute inference on a single patient record.

        Args:
            input_data: Dictionary of patient demographics and optional biosensors.

        Returns:
            PredictionResult dataclass with class predictions, probabilities, and disclaimers.
        """
        validated = self.validate_input_dict(input_data)
        imputed_features = [k for k in BIOSENSOR_FEATURES if np.isnan(validated[k])]

        # Construct single-row DataFrame aligned with canonical feature order
        row_df = pd.DataFrame([validated])[self.feature_names]

        # Execute pipeline (imputer + classifier)
        pred_label = str(self.pipeline.predict(row_df)[0])
        pred_probs = self.pipeline.predict_proba(row_df)[0]

        # Map class probabilities to class names
        class_prob_map: dict[str, float] = {}
        for c_idx, c_name in enumerate(self.classes):
            class_prob_map[c_name] = round(float(pred_probs[c_idx]), 4)

        return PredictionResult(
            predicted_class=pred_label,
            class_probabilities=class_prob_map,
            features_used=validated,
            imputed_features=imputed_features,
            model_name=self.model_name,
            model_version=self.model_version,
            is_research_prototype=True,
            disclaimer=RESEARCH_DISCLAIMER,
        )

    def predict_batch(
        self,
        batch_data: Sequence[dict[str, Any]] | pd.DataFrame,
    ) -> list[PredictionResult]:
        """Execute inference across multiple patient records.

        Args:
            batch_data: Sequence of patient dictionaries or a pandas DataFrame.

        Returns:
            List of PredictionResult instances.
        """
        if isinstance(batch_data, pd.DataFrame):
            records = batch_data.to_dict(orient="records")
        else:
            records = list(batch_data)

        return [self.predict_single(record) for record in records]


def build_cli_parser() -> argparse.ArgumentParser:
    """Construct command-line argument parser for standalone tabular inference."""
    parser = argparse.ArgumentParser(
        description="Arogya AI - Standalone Tabular Biosensor Risk Classifier (Research Prototype)",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--age", type=int, help="Patient age in years (1-120)")
    parser.add_argument("--gender", type=str, help="Patient gender: 1/male or 0/female")
    parser.add_argument("--smoking", type=int, choices=[1, 2, 3], help="Smoking history: 1=Non-smoker, 2=Ex-smoker, 3=Active-smoker")
    parser.add_argument("--imaginary-min", type=float, default=None, help="Imaginary permittivity minimum")
    parser.add_argument("--imaginary-avg", type=float, default=None, help="Imaginary permittivity average")
    parser.add_argument("--real-min", type=float, default=None, help="Real permittivity minimum")
    parser.add_argument("--real-avg", type=float, default=None, help="Real permittivity average")
    parser.add_argument("--json-input", type=str, help="Raw JSON string containing patient input record")
    parser.add_argument("--file", type=Path, help="Path to JSON file containing patient record or list of records")
    return parser


def main() -> None:
    """CLI entrypoint for standalone prediction."""
    parser = build_cli_parser()
    args = parser.parse_args()

    predictor = TabularPredictor()

    if args.file:
        with open(args.file, "r", encoding="utf-8") as f:
            data = json.load(f)
        if isinstance(data, list):
            results = predictor.predict_batch(data)
            print(json.dumps([r.to_dict() for r in results], indent=2))
        else:
            result = predictor.predict_single(data)
            print(json.dumps(result.to_dict(), indent=2))
        return

    if args.json_input:
        data = json.loads(args.json_input)
        result = predictor.predict_single(data)
        print(json.dumps(result.to_dict(), indent=2))
        return

    if args.age is not None and args.gender is not None and args.smoking is not None:
        input_data = {
            "Age": args.age,
            "Gender": args.gender,
            "Smoking": args.smoking,
            "Imaginary_Min": args.imaginary_min,
            "Imaginary_Avg": args.imaginary_avg,
            "Real_Min": args.real_min,
            "Real_Avg": args.real_avg,
        }
        result = predictor.predict_single(input_data)
        print(json.dumps(result.to_dict(), indent=2))
        return

    parser.print_help()


if __name__ == "__main__":
    main()

